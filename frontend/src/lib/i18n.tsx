type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (key: string, vars?: Record<string, string | number>) => string; tx: (serverText: string | null | undefined) => string };
const LangContext = createContext<Ctx | null>(null);

function applyToDocument(lang: Lang) {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
}

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("ar");
  setFormatLang(lang);

  useEffect(() => {
    let saved: Lang = "ar";
    try { if (localStorage.getItem("lang") === "en") saved = "en"; } catch {}
    setLangState(saved);
    applyToDocument(saved);
  }, []);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    applyToDocument(l);
    try { localStorage.setItem("lang", l); } catch {}
  }, []);

  const t = useCallback((key: string, vars?: Record<string, string | number>) => {
    let s = lang === "ar" ? AR[key] ?? key : EN[key] ?? humanize(key);
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    return s;
  }, [lang]);

  const tx = useCallback((text: string | null | undefined) => {
    if (!text) return "";
    if (lang !== "ar") return text;
    for (const [re, rep] of AR_PATTERNS) if (re.test(text)) return text.replace(re, rep);
    return AR[text] ?? text;
  }, [lang]);

  return <LangContext.Provider value={{ lang, setLang, t, tx }}>{children}</LangContext.Provider>;
}

export function useT() {
  const c = useContext(LangContext);
  if (!c) throw new Error("useT must be used inside LangProvider");
  return c;
}

export function LangSwitch({ className = "" }: { className?: string }) {
  const { lang, setLang } = useT();
  return (
    <button className={`btn-ghost ${className}`} onClick={() => setLang(lang === "ar" ? "en" : "ar")} aria-label="Switch language">
      <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.8" aria-hidden><circle cx="12" cy="12" r="9" /><path d="M3 12h18M12 3c2.5 2.7 3.8 5.7 3.8 9s-1.3 6.3-3.8 9c-2.5-2.7-3.8-5.7-3.8-9S9.5 5.7 12 3z" /></svg>
      {lang === "ar" ? "English" : "العربية"}
    </button>
  );
}
